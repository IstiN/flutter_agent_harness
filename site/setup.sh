# ── Interactive helpers ──────────────────────────────────────────────────────
# POSIX assignment discipline (gh-1596): `ask`/`ask_yn` print the answer on
# stdout and callers assign via command substitution — `var=$(ask …)` — so
# the exit code propagates (EOF under `set -eu` aborts the wizard, exactly
# like the old bare-call + `printf -v` shape). `ask_hidden` assigns BY NAME
# through `read -r "$1"` — the API key moves from the tty straight into the
# variable (echo suppressed via stty — dash has no `read -s`) and never
# passes through printf argv, where `ps` could catch it.
prompt() {
  printf '\033[1m%s\033[0m ' "$1" > /dev/tty
}

ask() { # ask TEXT [DEFAULT] — prints the answer on stdout
  local text="$1" default="${2:-}" value
  if [ -n "$default" ]; then
    prompt "$text [$default]"
  else
    prompt "$text"
  fi
  if ! read -r value < "$FAH_TTY" 2>/dev/tty; then
    printf '%s' "$default"
    return 1
  fi
  if [ -z "$value" ] && [ -n "$default" ]; then
    value=$default
  fi
  printf '%s\n' "$value"
  return 0
}

ask_hidden() { # ask_hidden VAR TEXT — reads hidden input into $VAR by name
  prompt "$2"
  # dash's read has NO -s (probed in the IT platform facts) — hide the
  # entry with stty on the controlling tty instead. `stty -g` snapshots
  # the full termios for a byte-exact restore (the EXIT trap re-runs it,
  # so even Ctrl-C mid-key re-enables echo). The value travels tty →
  # variable BY NAME and never rides printf argv, where ps could catch it.
  if [ -z "$FAH_STTY_SAVED" ]; then
    FAH_STTY_SAVED=$(stty -g < /dev/tty 2>/dev/null || true)
  fi
  stty -echo < /dev/tty 2>/dev/null
  local read_ok=0
  if read -r "$1" < "$FAH_TTY" 2>/dev/tty; then
    read_ok=1
  fi
  if [ -n "$FAH_STTY_SAVED" ]; then
    stty "$FAH_STTY_SAVED" < /dev/tty 2>/dev/null
    FAH_STTY_SAVED=""
  else
    stty echo < /dev/tty 2>/dev/null
  fi
  printf '\n' > /dev/tty
  [ "$read_ok" -eq 1 ] && return 0
  return 1
}

ask_yn() { # ask_yn TEXT [DEFAULT] — prints y or n on stdout
  local text="$1" default="${2:-y}" answer
  while true; do
    if [ "$default" = "y" ]; then
      prompt "$text [Y/n]"
    else
      prompt "$text [y/N]"
    fi
    if ! read -r answer < "$FAH_TTY" 2>/dev/tty; then
      printf '%s' "$default"
      return 1
    fi
    answer=${answer:-$default}
    case "$answer" in
      [Yy]|"" ) printf 'y\n'; return 0 ;;
      [Nn]    ) printf 'n\n'; return 0 ;;
    esac
    warn "please answer y or n"
  done
}

