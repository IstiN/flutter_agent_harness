# gh-1596: this script runs under `curl | sh` — the shebang is dead text and
# whatever `sh` resolves to executes it. POSIX sh only (dash + busybox ash +
# bash): no `printf -v`, no `[[`, no arrays, no `read -p/-a/-N`, no
# `${var,,}`, no `=~`. UT-1 (test/site/setup_sh_portability_test.dart) lints
# the dialect; UT-2 pins the regenerated bytes.

set -eu  # no pipefail: dash (Ubuntu sh) lacks it

