#!/usr/bin/env python3
"""gh-1630 — mechanical CWS resubmission compliance check (AC7/REG-1).

Asserts the Chrome Web Store rejection fixes on the CURRENT tree (and, with
--zip, on the built package). Exit 0 = resubmission-safe; exit 1 with
::error annotations = a violation that would fail store review again.
Wired into .github/workflows/browser-ext.yml on every PR touching
browser_ext/ or the engine loaders — red blocks merge.

Checks:
  AC1  no remote-code markers (jsdelivr/unpkg/cdns/https://cdn.) in any
       packaged-verbatim source under browser_ext/ (build artifacts
       excluded — the built zip is scanned wholesale by
       scripts/ext_package_guard.py check, which this script does NOT
       duplicate when --zip is passed);
  AC5  manifest: the five dead permissions absent; CSP
       'self' 'wasm-unsafe-eval', no remote origin; strict-JSON parseable
       once // comments are stripped (the packaged copy is fully strict);
  AC6  site/privacy.html carries all nine mandatory sections (data-sec
       anchors) in EN and RU; the store listing links the live URL;
  AC3  browser_ext/vendor.lock.json pins every artifact with sha256 and
       scripts/fetch_vendor_assets.sh is executable and build-wired.
"""

import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

DEAD_PERMISSIONS = {
    "contentSettings",
    "downloads",
    "fontSettings",
    "identity",
    "desktopCapture",
}

REMOTE_MARKER = re.compile(rb"jsdelivr|unpkg|cdnjs|https://cdn\.")

# browser_ext/ paths that are NOT packaged verbatim:
#   - build artifacts (gitignored, regenerated by the packaging build);
#   - the vendor.lock.json itself — the sanctioned record OF the source
#     URLs (the package carries the fetched binaries, not the lock);
#   - browser_ext/dart/ and browser_ext/test/ and browser_ext/e2e/ — the
#     Dart agent package (only its dart2js OUTPUT ships, as sw/agent.js,
#     which the zip scan covers), the node test suite, the Playwright
#     specs. Everything else under browser_ext/ ships byte-for-byte and
#     stays under this scan.
NOT_PACKAGED = (
    "browser_ext/panel/app/",
    "browser_ext/sw/agent.js",
    "browser_ext/sw/agent.js.map",
    "browser_ext/sw/agent.js.deps",
    "browser_ext/vendor/",
    "browser_ext/vendor.lock.json",
    "browser_ext/dart/",
    "browser_ext/test/",
    "browser_ext/e2e/",
)

MANDATORY_SECTIONS = {
    "collect",
    "handle",
    "storage",
    "sharing",
    "retention",
    "security",
    "children",
    "changes",
    "contact",
}

REQUIRED_ENGINES = {
    "quickjs",
    "pyodide",
    "sqljs",
    "webllm",
    "transformers",
    "litert",
}


def error(rule: str, detail: str) -> None:
    print(f"::error title={rule}::{detail}", file=sys.stderr)


def rel(path: str) -> str:
    return os.path.relpath(path, ROOT).replace(os.sep, "/")


def check_ac1_sources() -> int:
    failures = 0
    for dirpath, dirnames, filenames in os.walk(
        os.path.join(ROOT, "browser_ext")
    ):
        for fn in filenames:
            path = os.path.join(dirpath, fn)
            r = rel(path)
            if r.startswith(NOT_PACKAGED):
                continue
            try:
                with open(path, "rb") as f:
                    if REMOTE_MARKER.search(f.read()):
                        error(
                            "AC1-remote-code-source",
                            f"{r}: remote-code marker in packaged-verbatim "
                            "source — reviewers read the shipped tree "
                            "(gh-1630 I1)",
                        )
                        failures += 1
            except OSError:
                continue
    return failures


def check_ac5_manifest() -> int:
    failures = 0
    path = os.path.join(ROOT, "browser_ext", "manifest.json")
    raw = open(path, encoding="utf-8").read()
    # The SOURCE manifest carries // comments (Chrome tolerates them); the
    # packaged copy must be strict JSON — the build strips them, and
    # ext_package_guard check re-parses the zip's copy strictly.
    try:
        manifest = json.loads(
            re.sub(r"^\s*//.*$", "", raw, flags=re.M)
        )
    except json.JSONDecodeError as e:
        error("AC5-manifest-parse", f"browser_ext/manifest.json: {e}")
        return 1
    declared = set(manifest.get("permissions") or []) | set(
        manifest.get("optional_permissions") or []
    )
    resurrected = sorted(declared & DEAD_PERMISSIONS)
    if resurrected:
        error(
            "AC5-dead-permissions",
            f"browser_ext/manifest.json re-declares {', '.join(resurrected)} "
            "— gh-1630 removed them (CWS Purple Potassium)",
        )
        failures += 1
    csp = (manifest.get("content_security_policy") or {}).get(
        "extension_pages", ""
    )
    if "'wasm-unsafe-eval'" not in csp or "'self'" not in csp:
        error(
            "AC5-csp-wasm",
            f"extension_pages CSP {csp!r} lacks 'self' 'wasm-unsafe-eval' "
            "(gh-1630 I5 — the vendored wasm engines cannot boot without it)",
        )
        failures += 1
    if re.search(r"https?://", csp):
        error(
            "AC5-csp-remote",
            f"extension_pages CSP {csp!r} allows a remote origin",
        )
        failures += 1
    return failures


def check_ac6_privacy() -> int:
    failures = 0
    html = open(
        os.path.join(ROOT, "site", "privacy.html"), encoding="utf-8"
    ).read()
    for lang in ("en", "ru"):
        start = html.find(f'<section id="{lang}"')
        end = html.find("</section>", start) if start >= 0 else -1
        if start < 0 or end < 0:
            error("AC6-privacy-lang", f"privacy.html: {lang} block missing")
            failures += 1
            continue
        block = html[start:end]
        missing = [
            k for k in MANDATORY_SECTIONS if f'data-sec="{k}"' not in block
        ]
        if missing:
            error(
                "AC6-privacy-sections",
                f"privacy.html {lang} block missing mandatory sections: "
                f"{', '.join(sorted(missing))} — CWS Purple Nickel: "
                "omission of any section is not allowed",
            )
            failures += 1
    listing_path = os.path.join(
        ROOT, "browser_ext", "store", "listing.md"
    )
    listing = open(listing_path, encoding="utf-8").read()
    if "https://fa1.dev/privacy.html" not in listing:
        error(
            "AC6-listing-privacy-url",
            "browser_ext/store/listing.md does not link the live privacy "
            "policy URL (https://fa1.dev/privacy.html)",
        )
        failures += 1
    return failures


def check_ac3_lock() -> int:
    failures = 0
    lock_path = os.path.join(ROOT, "browser_ext", "vendor.lock.json")
    try:
        lock = json.load(open(lock_path, encoding="utf-8"))
    except (OSError, ValueError) as e:
        error("AC3-lock", f"browser_ext/vendor.lock.json unreadable: {e}")
        return 1
    engines = lock.get("engines") or {}
    missing_engines = REQUIRED_ENGINES - set(engines)
    if missing_engines:
        error(
            "AC3-lock-engines",
            f"vendor.lock.json missing engines: {', '.join(sorted(missing_engines))}",
        )
        failures += 1
    sha_re = re.compile(r"^[0-9a-f]{64}$")
    for name, engine in engines.items():
        version = engine.get("version")
        if not version:
            error("AC3-lock-version", f"vendor.lock.json: {name} unpinned")
            failures += 1
        for file in engine.get("files") or []:
            if not sha_re.match(file.get("sha256") or ""):
                error(
                    "AC3-lock-sha256",
                    f"vendor.lock.json: {name}/{file.get('name')} lacks a "
                    "sha256 pin",
                )
                failures += 1
            url = file.get("url") or ""
            # The URL must pin A version — the engine's own, or the pinned
            # dependency a vendored artifact rides (e.g. transformers 4.2.0
            # bundles onnxruntime-web 1.26.0-dev…; litert 0.12.1 imports
            # @litertjs/wasm-utils 2.5.0). A floating specifier (+esm with
            # no version) would re-resolve upstream — never shippable.
            if not re.search(r"\d+\.\d+\.\d+", url):
                error(
                    "AC3-lock-url-pin",
                    f"vendor.lock.json: {name}/{file.get('name')} URL is "
                    f"not version-pinned: {url}",
                )
                failures += 1
    fetcher = os.path.join(ROOT, "scripts", "fetch_vendor_assets.sh")
    if not os.path.isfile(fetcher) or not os.access(fetcher, os.X_OK):
        error("AC3-fetcher", "scripts/fetch_vendor_assets.sh missing/exec")
        failures += 1
    build = open(
        os.path.join(ROOT, "scripts", "build_browser_ext.sh"),
        encoding="utf-8",
    ).read()
    if "fetch_vendor_assets.sh" not in build:
        error(
            "AC3-build-wiring",
            "scripts/build_browser_ext.sh does not fetch vendor assets "
            "from the lock",
        )
        failures += 1
    return failures


def main() -> int:
    failures = 0
    failures += check_ac1_sources()
    failures += check_ac5_manifest()
    failures += check_ac6_privacy()
    failures += check_ac3_lock()

    if failures:
        error(
            "cws-compliance",
            f"{failures} violation(s) — this resubmission would be rejected "
            "again; fix before merge (gh-1630 REG-1: red blocks merge)",
        )
        return 1
    print("cws-compliance: OK (AC1 sources / AC5 manifest / AC6 privacy / "
          "AC3 lock all green)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
