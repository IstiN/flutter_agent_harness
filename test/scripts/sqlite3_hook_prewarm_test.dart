// Unit tests for scripts/sqlite3_hook_prewarm.dart (gh-2074).
//
// gh-2074: the play leg (build-mobile.yml) went red on THREE jobs when a
// GitHub release-download brownout served 504 pages to package:sqlite3's
// native-assets hook, which (in the released versions pinned here — 3.7.0
// via flutter_app/pubspec.lock, 3.9.1 floating at the root) hashes the
// response body WITHOUT honoring the HTTP status. The 504 page's SHA-256
// (bef140a1…) is a constant for every caller, so the hook reports it as a
// "Hash of downloaded file … mismatch" and exits 255 mid-build. The cure
// is a pre-warm of the hook's content-addressed cache that DOES check the
// status, retries with backoff, and only ever writes hash-verified bytes:
//
//   <pkg>/.dart_tool/hooks_runner/shared/sqlite3/build/download-<hash8>/<libname>
//
// The layout is not invented — it is the observed reuse path of the hook
// itself (sqlite3 3.9.1's `downloadIntoOutputDirectoryShared`):
// dirname = 'download-' + assetHash.substring(0, 8), filename = the target
// OS's libraryFileName('sqlite3', DynamicLoadingBundled()). The path pin
// below (linux-x64 → download-0a658527) was captured from a live hook run
// on 2026-11-09 and guards against layout drift.
import 'dart:convert' show jsonEncode;
import 'dart:io';
import 'dart:typed_data';

import 'package:crypto/crypto.dart';
import 'package:test/test.dart';

import '../../scripts/sqlite3_hook_prewarm.dart' as prewarm;

const defaultUrlPattern =
    'https://github.com/simolus3/sqlite3.dart/releases/download/'
    r'$RELEASE_TAG/$FILENAME';

String shaOf(List<int> bytes) => sha256.convert(bytes).toString();

Uint8List bytesOf(String s) => Uint8List.fromList(s.codeUnits);

/// A minimal asset_hashes.dart in the exact released shape (see
/// sqlite3-3.7.0 / sqlite3-3.9.1 lib/src/hook/asset_hashes.dart). The
/// pinned hashes are the REAL shas of the bytes the test's fetcher serves
/// for [assets] — the same invariant the released file carries.
String fixtureAssetHashesSource(String releaseTag, Iterable<String> assets) {
  final entries = [
    for (final asset in assets)
      "  '$asset': '${shaOf(contentFor(asset))}',",
  ].join('\n');
  return '''
// This file contains hashes of SQLite binaries downloaded by the default hook.
// Generated by tool/write_asset_hashes.dart

// dart format off
const String? releaseTag = '$releaseTag';

const Map<String, String> assetNameToSha256Hash = {
$entries
};
''';
}

/// The bytes the test fetcher serves for a release asset — the fixture
/// "binary".
Uint8List contentFor(String asset) => bytesOf('content-of-$asset');

/// Writes a fake "resolved package" tree: a package_config.json naming a
/// sqlite3 root that carries a fixture asset_hashes.dart.
(Directory, Directory, String) fixturePackage(
  String releaseTag,
  Iterable<String> assets,
) {
  final tmp = Directory.systemTemp.createTempSync('fah-prewarm-test-');
  addTearDown(() => tmp.deleteSync(recursive: true));
  final pkgRoot = Directory(
    '${tmp.path}${Platform.pathSeparator}fixture_sqlite3',
  )..createSync(recursive: true);
  final hashesPath =
      '${pkgRoot.path}${Platform.pathSeparator}lib${Platform.pathSeparator}'
      'src${Platform.pathSeparator}hook${Platform.pathSeparator}'
      'asset_hashes.dart';
  File(hashesPath)
    ..parent.createSync(recursive: true)
    ..writeAsStringSync(fixtureAssetHashesSource(releaseTag, assets));
  final appDir = Directory('${tmp.path}${Platform.pathSeparator}app')
    ..createSync();
  final dotDartTool = Directory('${appDir.path}${Platform.pathSeparator}.dart_tool')
    ..createSync();
  final config = {
    'packages': [
      {'name': 'other_pkg', 'rootUri': 'file:///nowhere/other'},
      {
        'name': 'sqlite3',
        'rootUri': Uri.file(pkgRoot.path).toString(),
      },
    ],
  };
  File(
    '${dotDartTool.path}${Platform.pathSeparator}package_config.json',
  ).writeAsStringSync(jsonEncode(config));
  return (tmp, appDir, hashesPath);
}

void main() {
  group('parseAssetHashes', () {
    test('parses release tag and hash map', () {
      final hashes = prewarm.parseAssetHashes(
        fixtureAssetHashesSource(
          'sqlite3-3.7.0',
          ['libsqlite3.x64.linux.so', 'libsqlite3.arm64.android.so'],
        ),
      );
      expect(hashes.releaseTag, 'sqlite3-3.7.0');
      expect(hashes.assetNameToSha256Hash['libsqlite3.x64.linux.so'],
          shaOf(contentFor('libsqlite3.x64.linux.so')));
      expect(hashes.assetNameToSha256Hash, hasLength(2));
    });

    test('parses a null release tag (pre-release shape)', () {
      final source = fixtureAssetHashesSource(
        'sqlite3-3.7.0',
        ['libsqlite3.x64.linux.so'],
      ).replaceFirst("= 'sqlite3-3.7.0'", '= null');
      final hashes = prewarm.parseAssetHashes(source);
      expect(hashes.releaseTag, isNull);
    });

    test('a null release tag cannot build a download URL', () {
      final source = fixtureAssetHashesSource(
        'x',
        ['libsqlite3.x64.linux.so'],
      ).replaceFirst("= 'x'", '= null');
      final hashes = prewarm.parseAssetHashes(source);
      expect(
        () => prewarm.downloadUriFor(
          hashes: hashes,
          urlPattern: defaultUrlPattern,
          assetName: 'libsqlite3.x64.linux.so',
        ),
        throwsA(isA<prewarm.PrewarmException>()),
      );
    });
  });

  group('asset filename mapping (mirrors package:sqlite3 releases)', () {
    test('linux/android assets are .so with the lib prefix', () {
      expect(prewarm.assetFilenameFor('linux', 'x64'),
          'libsqlite3.x64.linux.so');
      expect(prewarm.assetFilenameFor('android', 'arm64'),
          'libsqlite3.arm64.android.so');
      expect(prewarm.assetFilenameFor('android', 'ia32'),
          'libsqlite3.ia32.android.so');
    });

    test('apple assets are .dylib (ios_sim is the release os name)', () {
      expect(prewarm.assetFilenameFor('macos', 'arm64'),
          'libsqlite3.arm64.macos.dylib');
      expect(prewarm.assetFilenameFor('ios', 'arm64'),
          'libsqlite3.arm64.ios.dylib');
      expect(prewarm.assetFilenameFor('ios_sim', 'x64'),
          'libsqlite3.x64.ios_sim.dylib');
    });

    test('windows assets carry no lib prefix and are .dll', () {
      expect(prewarm.assetFilenameFor('windows', 'x64'),
          'sqlite3.x64.windows.dll');
    });
  });

  group('cached filename mapping (mirrors the hook reuse path)', () {
    test('linux/android cache as libsqlite3.so', () {
      expect(prewarm.cachedFilenameFor('linux'), 'libsqlite3.so');
      expect(prewarm.cachedFilenameFor('android'), 'libsqlite3.so');
    });

    test('apple caches as libsqlite3.dylib, windows as sqlite3.dll', () {
      expect(prewarm.cachedFilenameFor('macos'), 'libsqlite3.dylib');
      expect(prewarm.cachedFilenameFor('ios'), 'libsqlite3.dylib');
      expect(prewarm.cachedFilenameFor('ios_sim'), 'libsqlite3.dylib');
      expect(prewarm.cachedFilenameFor('windows'), 'sqlite3.dll');
    });
  });

  group('cache layout', () {
    // Observed live on 2026-11-09: the sqlite3 3.9.1 hook reused
    // .dart_tool/hooks_runner/shared/sqlite3/build/download-0a658527/libsqlite3.so
    // for libsqlite3.x64.linux.so (hash 0a65852703763619a7a34633b4959b3…).
    // If the hook's content-addressed layout ever drifts, this pin is the
    // first thing that breaks — update the script TOGETHER with this test.
    test('matches the hook reuse path observed live', () {
      expect(
        prewarm.cachedFilePath(
          sharedDir: '/w/.dart_tool/hooks_runner/shared',
          sha256:
              '0a65852703763619a7a34633b4959b3b86c4103804a4dfe4e8b27b5de1c0647b',
          os: 'linux',
        ),
        '/w/.dart_tool/hooks_runner/shared/sqlite3/build/'
        'download-0a658527/libsqlite3.so',
      );
    });

    test('dir name is the first 8 hex of the asset hash', () {
      expect(
        prewarm.cacheDirNameFor(
            '949965f0eba976f707ae364cdcb42c342b5f0626081f8d7f0378fb7b52848772'),
        'download-949965f0',
      );
    });
  });

  group('expandTargets', () {
    test('a bare os expands to all supported ABIs of that os', () {
      expect(prewarm.expandTargets('android'), hasLength(4));
      expect(
        prewarm
            .expandTargets('android')
            .map((t) => '${t.os}-${t.arch}')
            .toSet(),
        {'android-arm', 'android-arm64', 'android-ia32', 'android-x64'},
      );
    });

    test('a pinned os-arch expands to exactly one target', () {
      final t = prewarm.expandTargets('android-arm64');
      expect(t, hasLength(1));
      expect('${t.single.os}-${t.single.arch}', 'android-arm64');
    });

    test('host resolves against the injected platform', () {
      final t = prewarm.expandTargets('host', hostOs: 'linux', hostArch: 'x64');
      expect('${t.single.os}-${t.single.arch}', 'linux-x64');
    });

    // The 2026-11-09 CI red: this shard ran on ubuntu-24.04-arm and the
    // injected platform was IGNORED — expandTargets fell back to the real
    // machine (linux-arm64) and expected 'linux-x64' failed. A fully
    // injected platform must be host-independent: this assertion reds on
    // ANY host when the injection is dropped (an x64 dev box could never
    // see it — the real platform coincidentally matched the injection).
    test('a fully injected host never consults the real machine', () {
      final t =
          prewarm.expandTargets('host', hostOs: 'macos', hostArch: 'arm64');
      expect('${t.single.os}-${t.single.arch}', 'macos-arm64',
          reason:
              'the injected platform must win over Platform.operatingSystem/'
              'Abi.current() — the unit tests run on x64 AND arm64 shards');
    });

    test('a partial host injection fills the missing side from the machine',
        () {
      final osInjected = prewarm.expandTargets('host', hostOs: 'linux');
      expect(osInjected.single.os, 'linux',
          reason: 'the injected os overrides, the real machine fills the arch');
      final archInjected = prewarm.expandTargets('host', hostArch: 'x64');
      expect(archInjected.single.arch, 'x64',
          reason: 'the injected arch overrides, the real machine fills the os');
    });

    test('an injected platform is still validated (loud on unknown os/arch)',
        () {
      expect(
        () => prewarm.expandTargets('host',
            hostOs: 'fuchsia', hostArch: 'x64'),
        throwsA(isA<ArgumentError>()),
      );
      expect(
        () => prewarm.expandTargets('host',
            hostOs: 'linux', hostArch: 'mips'),
        throwsA(isA<ArgumentError>()),
      );
    });

    test('unknown os or arch is a loud error, never a silent no-op', () {
      expect(() => prewarm.expandTargets('fuchsia'),
          throwsA(isA<ArgumentError>()));
      expect(() => prewarm.expandTargets('android-mips'),
          throwsA(isA<ArgumentError>()));
    });
  });

  group('fetchVerified', () {
    late Directory tmp;
    setUp(() {
      tmp = Directory.systemTemp.createTempSync('fah-prewarm-fetch-');
      addTearDown(() => tmp.deleteSync(recursive: true));
    });

    Uri uriFor(String name) => Uri.parse('https://example.test/$name');

    test('writes hash-verified bytes and leaves no tmp sibling', () async {
      final content = bytesOf('real sqlite3 binary bytes');
      final dest = File('${tmp.path}${Platform.pathSeparator}libsqlite3.so');
      final got = await prewarm.fetchVerified(
        fetch: (_) async => Stream.value(content),
        uri: uriFor('libsqlite3.x64.linux.so'),
        expectedSha256: shaOf(content),
        destination: dest,
        attempts: 3,
        retryDelay: Duration.zero,
        timeoutPerAttempt: const Duration(seconds: 10),
      );
      expect(got.readAsStringSync(), 'real sqlite3 binary bytes');
      expect(
        dest.parent
            .listSync()
            .whereType<File>()
            .where((f) => f.path.endsWith('.tmp')),
        isEmpty,
      );
    });

    test('retries a brownout (non-200) and succeeds on a later attempt',
        () async {
      final content = bytesOf('good bytes after the 504s');
      final dest = File('${tmp.path}${Platform.pathSeparator}libsqlite3.so');
      var calls = 0;
      final got = await prewarm.fetchVerified(
        fetch: (_) async {
          calls++;
          if (calls <= 2) {
            throw prewarm.HttpStatusException(uriFor('x'), 504);
          }
          return Stream.value(content);
        },
        uri: uriFor('x'),
        expectedSha256: shaOf(content),
        destination: dest,
        attempts: 3,
        retryDelay: Duration.zero,
        timeoutPerAttempt: const Duration(seconds: 10),
      );
      expect(calls, 3);
      expect(got.readAsStringSync(), 'good bytes after the 504s');
    });

    test('exhausted retries fail loudly naming the url and the status',
        () async {
      final dest = File('${tmp.path}${Platform.pathSeparator}libsqlite3.so');
      await expectLater(
        prewarm.fetchVerified(
          fetch: (_) async => throw prewarm.HttpStatusException(uriFor('x'), 429),
          uri: uriFor('x'),
          expectedSha256: shaOf(bytesOf('unused')),
          destination: dest,
          attempts: 3,
          retryDelay: Duration.zero,
          timeoutPerAttempt: const Duration(seconds: 10),
        ),
        throwsA(
          isA<prewarm.PrewarmException>()
              .having((e) => e.message, 'message', contains('https://example.test/x'))
              .having((e) => e.message, 'message', contains('429')),
        ),
      );
      expect(dest.existsSync(), isFalse,
          reason: 'a failed download must never leave bytes in the cache');
    });

    test('a corrupt body is never written — hash gate before rename',
        () async {
      final dest = File('${tmp.path}${Platform.pathSeparator}libsqlite3.so');
      var calls = 0;
      await expectLater(
        prewarm.fetchVerified(
          // The 504-page class: HTTP 200-ish body whose hash ≠ the pin
          // (truncated transfer, lying proxy). Retryable — a corrupt body
          // burns the attempts before failing loudly.
          fetch: (_) async {
            calls++;
            return Stream.value(bytesOf('<html>504 Gateway</html>'));
          },
          uri: uriFor('x'),
          expectedSha256: shaOf(bytesOf('real bytes')),
          destination: dest,
          attempts: 2,
          retryDelay: Duration.zero,
          timeoutPerAttempt: const Duration(seconds: 10),
        ),
        throwsA(isA<prewarm.PrewarmException>()),
      );
      expect(calls, 2, reason: 'a hash mismatch is retryable like a 5xx');
      expect(dest.existsSync(), isFalse);
    });
  });

  group('prewarmPackage end-to-end (fixture package)', () {
    late Directory tmp;
    late Directory appDir;
    const fixtureAssets = [
      'libsqlite3.x64.linux.so',
      'libsqlite3.arm.android.so',
      'libsqlite3.arm64.android.so',
      'libsqlite3.ia32.android.so',
      'libsqlite3.x64.android.so',
    ];
    setUp(() {
      final fixture = fixturePackage('sqlite3-9.9.9-test', fixtureAssets);
      tmp = fixture.$1;
      appDir = fixture.$2;
    });

    prewarm.StreamFetcher fetcher(Map<String, Uint8List> byAsset) {
      return (uri) async {
        final name = uri.pathSegments.last;
        final hit = byAsset[name];
        if (hit == null) {
          throw prewarm.HttpStatusException(uri, 404);
        }
        return Stream.value(hit);
      };
    }

    test('seeds the hook cache with hash-verified bytes', () async {
      final report = await prewarm.prewarmPackage(
        packageDir: appDir,
        targets: prewarm.expandTargets('linux-x64'),
        urlPatternOverride: defaultUrlPattern,
        sharedDirOverride:
            Directory('${tmp.path}${Platform.pathSeparator}shared'),
        fetchOverride: fetcher({
          'libsqlite3.x64.linux.so': contentFor('libsqlite3.x64.linux.so'),
        }),
        onNote: (_) {},
      );
      expect(report.downloaded, hasLength(1));
      expect(report.skipped, isEmpty);
      final cached = File(
        '${tmp.path}${Platform.pathSeparator}shared'
        '${Platform.pathSeparator}sqlite3${Platform.pathSeparator}build'
        '${Platform.pathSeparator}download-${shaOf(contentFor('libsqlite3.x64.linux.so')).substring(0, 8)}'
        '${Platform.pathSeparator}libsqlite3.so',
      );      expect(cached.existsSync(), isTrue);
      expect(shaOf(cached.readAsBytesSync()),
          shaOf(contentFor('libsqlite3.x64.linux.so')));
    });

    test('is idempotent — a verified cache hit performs no fetch', () async {
      final shared = Directory('${tmp.path}${Platform.pathSeparator}shared');
      final fetch = fetcher({
        'libsqlite3.x64.linux.so': contentFor('libsqlite3.x64.linux.so'),
      });
      await prewarm.prewarmPackage(
        packageDir: appDir,
        targets: prewarm.expandTargets('linux-x64'),
        urlPatternOverride: defaultUrlPattern,
        sharedDirOverride: shared,
        fetchOverride: fetch,
        onNote: (_) {},
      );
      // A second run must not touch the network at all.
      final report = await prewarm.prewarmPackage(
        packageDir: appDir,
        targets: prewarm.expandTargets('linux-x64'),
        urlPatternOverride: defaultUrlPattern,
        sharedDirOverride: shared,
        fetchOverride: (uri) => throw StateError(
            'must not fetch $uri — the cache was already verified'),
        onNote: (_) {},
      );
      expect(report.downloaded, isEmpty);
      expect(report.skipped, hasLength(1));
    });

    test('repairs a corrupt cache entry in place', () async {
      final shared = Directory('${tmp.path}${Platform.pathSeparator}shared');
      final good = contentFor('libsqlite3.x64.linux.so');
      await prewarm.prewarmPackage(
        packageDir: appDir,
        targets: prewarm.expandTargets('linux-x64'),
        urlPatternOverride: defaultUrlPattern,
        sharedDirOverride: shared,
        fetchOverride: fetcher({'libsqlite3.x64.linux.so': good}),
        onNote: (_) {},
      );
      // Corrupt the cache the way a torn write or a stale version would.
      final cached = File(
        '${shared.path}${Platform.pathSeparator}sqlite3'
        '${Platform.pathSeparator}build'
        '${Platform.pathSeparator}download-${shaOf(good).substring(0, 8)}'
        '${Platform.pathSeparator}libsqlite3.so',
      );
      cached.writeAsStringSync('garbage');
      final report = await prewarm.prewarmPackage(
        packageDir: appDir,
        targets: prewarm.expandTargets('linux-x64'),
        urlPatternOverride: defaultUrlPattern,
        sharedDirOverride: shared,
        fetchOverride: fetcher({'libsqlite3.x64.linux.so': good}),
        onNote: (_) {},
      );
      expect(report.downloaded, hasLength(1), reason: 'corrupt entry re-fetched');
      expect(shaOf(cached.readAsBytesSync()), shaOf(good));
    });

    test('seeds multiple targets (the android ABI set) in one run', () async {
      final shared = Directory('${tmp.path}${Platform.pathSeparator}shared');
      final report = await prewarm.prewarmPackage(
        packageDir: appDir,
        targets: prewarm.expandTargets('android'),
        urlPatternOverride: defaultUrlPattern,
        sharedDirOverride: shared,
        fetchOverride: fetcher({
          'libsqlite3.arm.android.so': contentFor('libsqlite3.arm.android.so'),
          'libsqlite3.arm64.android.so':
              contentFor('libsqlite3.arm64.android.so'),
          'libsqlite3.ia32.android.so': contentFor('libsqlite3.ia32.android.so'),
          'libsqlite3.x64.android.so': contentFor('libsqlite3.x64.android.so'),
        }),
        onNote: (_) {},
      );
      expect(report.downloaded, hasLength(4));
    });

    test('a missing sqlite3 in the package config is a loud error', () async {
      final empty = Directory.systemTemp.createTempSync('fah-prewarm-empty-');
      addTearDown(() => empty.deleteSync(recursive: true));
      Directory('${empty.path}${Platform.pathSeparator}.dart_tool')
          .createSync();
      File(
        '${empty.path}${Platform.pathSeparator}.dart_tool'
        '${Platform.pathSeparator}package_config.json',
      ).writeAsStringSync(jsonEncode({
        'packages': [
          {'name': 'a', 'rootUri': 'file:///nowhere/a'},
        ],
      }));
      await expectLater(
        prewarm.prewarmPackage(
          packageDir: empty,
          targets: prewarm.expandTargets('host', hostOs: 'linux', hostArch: 'x64'),
          onNote: (_) {},
        ),
        throwsA(isA<prewarm.PrewarmException>()),
      );
    });
  });
}
